func LookupColo(raw string) (code, city, country string) {
	cleaned := strings.TrimSpace(strings.ToUpper(raw))
	// id.server responses look like "FRA" or "fra01" or "288f12"
	if len(cleaned) >= 3 {
		letters := cleaned[:3]
		if meta, ok := coloTable[letters]; ok {
			return letters, meta.City, meta.Country
		}
		// Sometimes id.server returns "AMS-..."
		if idx := strings.IndexByte(cleaned, '-'); idx == 3 {
			if meta, ok := coloTable[cleaned[:3]]; ok {
				return cleaned[:3], meta.City, meta.Country
			}
		}
		isAlpha := true
		for i := 0; i < 3; i++ {
			if letters[i] < 'A' || letters[i] > 'Z' {
				isAlpha = false
				break
			}
		}
		if isAlpha {
			return letters, "Узел " + letters, "Cloudflare"
		}
	}
	return "CF", "Узел Cloudflare", "Европа"
}
